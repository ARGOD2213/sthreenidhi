-- 1. LOAN_STATUS_NEW: what do the rows mean? one summary line per IS_CLOSED value
SELECT IS_CLOSED, COUNT(*) AS ROWS_, COUNT(DISTINCT SHG_MEMBER_LOAN_ACCNO) AS LOANS,
       SUM(LOAN_DUE) AS SUM_LOAN_DUE, SUM(LOAN_EMI) AS SUM_EMI, SUM(AMOUNT_PAID) AS SUM_PAID,
       SUM(OUTSTANDING) AS SUM_OUTSTANDING, SUM(ADVANCE_COLL) AS SUM_ADVANCE,
       MIN(DUE_DATE) AS MIN_DUE, MAX(DUE_DATE) AS MAX_DUE, MAX(IS_CLOSED_UPDATE_TIME) AS LAST_UPDATE
FROM SN.SHG_MEMBER_LOAN_STATUS_NEW WITH (NOLOCK)
GROUP BY IS_CLOSED;

-- 2. LOAN_STATUS_NEW: open loans that have an amount due (look at the columns together)
SELECT TOP 10 SHG_MEMBER_LOAN_ACCNO, LOAN_DISBURSEMENT_DATE, LOAN_AMOUNT, INST_NO, DUE_DATE, LOAN_DUE, LOAN_EMI,
       AMOUNT_PAID, OUTSTANDING, IS_CLOSED, LOAN_CLOSER, ADVANCE_COLL
FROM SN.SHG_MEMBER_LOAN_STATUS_NEW WITH (NOLOCK)
WHERE IS_CLOSED = 0 AND LOAN_DUE > 0
ORDER BY DUE_DATE DESC;

-- 3. LOAN_STATUS_NEW: open loans with NO amount due
SELECT TOP 5 SHG_MEMBER_LOAN_ACCNO, LOAN_DISBURSEMENT_DATE, LOAN_AMOUNT, INST_NO, DUE_DATE, LOAN_DUE, LOAN_EMI,
       AMOUNT_PAID, OUTSTANDING, IS_CLOSED, ADVANCE_COLL
FROM SN.SHG_MEMBER_LOAN_STATUS_NEW WITH (NOLOCK)
WHERE IS_CLOSED = 0 AND LOAN_DUE = 0 AND DUE_DATE >= '2026-09-01'
ORDER BY DUE_DATE DESC;

-- 4. Is it one row per loan, or several (one per instalment)?
SELECT TOP 5 SHG_MEMBER_LOAN_ACCNO, COUNT(*) AS ROWS_FOR_LOAN
FROM SN.SHG_MEMBER_LOAN_STATUS_NEW WITH (NOLOCK)
GROUP BY SHG_MEMBER_LOAN_ACCNO
HAVING COUNT(*) > 1
ORDER BY COUNT(*) DESC;

-- 5. Does it match the loans the dashboard shows as OPEN?
SELECT COUNT(*) AS OPEN_LOANS_MATCHED,
       SUM(CASE WHEN S.IS_CLOSED = 0 THEN 1 ELSE 0 END) AS NOT_CLOSED_IN_STATUS,
       SUM(CASE WHEN S.IS_CLOSED = 1 THEN 1 ELSE 0 END) AS CLOSED_IN_STATUS_BUT_OPEN_IN_MCP,
       SUM(CASE WHEN S.LOAN_DUE > 0 THEN 1 ELSE 0 END) AS LOANS_WITH_DUE,
       SUM(S.LOAN_DUE) AS TOTAL_DUE
FROM SHG_MEMBER_MCP_INFO M WITH (NOLOCK)
JOIN SN.SHG_MEMBER_LOAN_STATUS_NEW S WITH (NOLOCK) ON S.SHG_MEMBER_LOAN_ACCNO = M.SHG_MEMBER_LOAN_ACCNO
WHERE M.LOAN_STATUS = 'OPEN';

-- 6. How many OPEN loans have no row at all in the status table?
SELECT COUNT(*) AS OPEN_LOANS_WITHOUT_STATUS_ROW
FROM SHG_MEMBER_MCP_INFO M WITH (NOLOCK)
WHERE M.LOAN_STATUS = 'OPEN'
  AND NOT EXISTS (SELECT 1 FROM SN.SHG_MEMBER_LOAN_STATUS_NEW S WITH (NOLOCK) WHERE S.SHG_MEMBER_LOAN_ACCNO = M.SHG_MEMBER_LOAN_ACCNO);

-- 7. TARGET: values and units in the table the dashboard uses, per financial year
SELECT FY_YEAR, COUNT(*) AS ROWS_, SUM(Target_Amount) AS SUM_TARGET_AMOUNT, SUM(Target_Amounts) AS SUM_TARGET_AMOUNTS,
       SUM(TARGET_AMOUNT_MONTHLY) AS SUM_MONTHLY, MAX(Target_Amount) AS MAX_ONE_ROW, MAX(CREATED_DATE) AS LAST_CREATED
FROM dbo.Livelihood_Mandalwise_Target_FY18 WITH (NOLOCK)
GROUP BY FY_YEAR ORDER BY FY_YEAR;

